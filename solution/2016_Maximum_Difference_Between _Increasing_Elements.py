## Optimized Solution
class SolutionOptimized(object):
    """
    - Key Idea and Optimal Solution (Greedy Approach):

        The most efficient way to solve this problem is to use a single pass through 
        the array while keeping track of the minimum element encountered so far.

        Here's the intuition:

        To maximize nums[j] - nums[i] with i < j, for any nums[j], you want to find
        the smallest possible nums[i] that appeared before nums[j].
        
    - Algorithm:

        1. Initialize max_diff to -1. This will store our result.
        2. Initialize min_so_far to the first element of the array, nums[0]. This will track the minimum value encountered as we iterate.
        3. Iterate through the nums array starting from the second element (index 1). For each element nums[j]:
            If nums[j] > min_so_far:
                - This means we found a potential increasing pair. Calculate the current difference: nums[j] - min_so_far.
                Update max_diff = max(max_diff, nums[j] - min_so_far).
            Else (nums[j] <= min_so_far):
                - The current element nums[j] is smaller than or equal to the min_so_far. This nums[j] now becomes a new candidate for the min_so_far for future elements.
                - Update min_so_far = nums[j].
        4. After iterating through the entire array, return max_diff.
    
    - Why this works (Time and Space Complexity):

    Time Complexity: O(n)
        - We iterate through the array only once. Each step inside the loop takes constant time.
    Space Complexity: O(1)
        - We only use a few variables (max_diff, min_so_far), which consume constant extra space.
    """
    def maximumDifference(self, nums):
        min_val = nums[0]
        max_diff = -1
        for num in nums[1:]:
            if num > min_val:
                max_diff = max(max_diff, num - min_val)
            else:
                min_val = num
        return max_diff

