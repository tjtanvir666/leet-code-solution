class Solution(object):
    def maximumDifference(self, nums):
        """
        :type nums: List[int]
        :rtype: int
        """
        list_diff = []
        for i in range(len(nums)):
            for j in range(len(nums)):
                if (i < j) and (nums[i] < nums[j]):
                    list_diff.append(nums[j] - nums[i])
        if len(list_diff)==0:
            return -1
        else :
            list_diff.sort(reverse=True)
            #print(list_diff)
            result = list_diff[0]
            #print(result)
            return result
        

